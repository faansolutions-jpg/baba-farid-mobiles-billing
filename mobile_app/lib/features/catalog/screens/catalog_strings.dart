  /// Looks up [key] in the current language, falling back to English,
  /// then to the key itself — never throws.
  static String tr(String key) {
    final langMap = _strings[language] ?? _strings['en']!;
    return langMap[key] ?? _strings['en']![key] ?? key;
  }

  /// Looks up [key] in [language] without changing the current language.
  static String trIn(String key, String language) {
    final langMap = _strings[language] ?? _strings['en']!;
    return langMap[key] ?? _strings['en']![key] ?? key;
  }

  /// Replaces `{name}` placeholders in a looked-up string.
  static String trArgs(String key, Map<String, Object> args) {
    var value = tr(key);
    args.forEach((name, arg) {
      value = value.replaceAll('{$name}', arg.toString());
    });
    return value;
  }

  static bool get isUrdu => language == 'ur';

  /// All keys available in English (the reference language).
  static List<String> get allKeys => _strings['en']!.keys.toList();

  /// True when every Urdu entry exists for every English key.
  static bool get urduIsComplete {
    final en = _strings['en']!;
    final ur = _strings['ur']!;
    return en.keys.every((k) => ur.containsKey(k) && ur[k]!.isNotEmpty);
  }
}
