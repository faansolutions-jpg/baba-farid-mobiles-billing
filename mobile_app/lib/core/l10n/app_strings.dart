  /// Looks up [key] in [language] ('en' or 'ur').
  /// Falls back to English, then to the key itself — never throws.
  static String tr(String key, {String language = 'en'}) {
    final langMap = _strings[language] ?? _strings['en']!;
    return langMap[key] ?? _strings['en']![key] ?? key;
  }

  /// Convenience lookup using the currently selected language.
  static String trFor(String key, WidgetRef ref) =>
      tr(key, language: ref.watch(languageProvider));

  static bool isUrdu(String language) => language == 'ur';

  /// Text direction for a language code: Urdu is RTL, English is LTR.
  static TextDirection textDirection(String language) =>
      isUrdu(language) ? TextDirection.rtl : TextDirection.ltr;

  /// All keys available in English (the reference language).
  static List<String> get allKeys => _strings['en']!.keys.toList();

  /// True when every Urdu entry exists for every English key.
  static bool get urduIsComplete {
    final en = _strings['en']!;
    final ur = _strings['ur']!;
    return en.keys.every((k) => ur.containsKey(k) && ur[k]!.isNotEmpty);
  }
